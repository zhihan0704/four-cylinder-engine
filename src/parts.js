const partExport = {};
for (const [id, def] of Object.entries(base)) {
  partExport[id] = { ...def, id, variants: [] };
}

const V = (baseId, index, suffix, enSuffix) => {
  const b = base[baseId];
  return {
    ...b,
    id: `${baseId}-${index}`,
    variant: index,
    name: `${b.name} #${index + 1}`,
    en: `${b.en} #${index + 1}`,
    function: b.function,
    specs: b.specs,
  };
};

// Cylinder-specific entries are created on demand by the model code.
export function variantPart(baseId, index) {
  if (index == null) return partExport[baseId];
  return V(baseId, index);
}

export function defineCylinderVariants() {
  const variantBases = ['piston', 'rings', 'pin', 'rod', 'rodBearing', 'intakeValve', 'exhaustValve', 'valveSpring', 'injector'];
  for (const baseId of variantBases) {
    for (let i = 0; i < 4; i++) partExport[`${baseId}-${i}`] = V(baseId, i);
  }
  // shared multi-instance sub-parts use the generic id; hover state can pass a cylinder index
}
defineCylinderVariants();

